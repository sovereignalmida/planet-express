FILE_NAME = "pe-remote.yml"
STATUS_NAME = "remote_routes.json"
OWNER = "remote-ingress"
PREFIX = "pe-"
VERIFY_TIMEOUT_S = 15
API_TIMEOUT_S = 5
MAX_PAGES = 50
MAX_RULE = 1024
_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,62}$")
_HOST_RULE = re.compile(r"Host\(\s*`([^`]{1,253})`\s*\)")
_HOSTS = r"Host\(\s*`[^`]{1,253}`\s*\)(?:\s*\|\|\s*Host\(\s*`[^`]{1,253}`\s*\))*"
_HOST_GROUP = re.compile(rf"^(?:{_HOSTS}|\(\s*{_HOSTS}\s*\))")
# The only remote rule shapes forwarded: every request they match is for a host PE checked (Codex, release D).
_RULE_SHAPE = re.compile(rf"^(?:{_HOSTS}|\(\s*{_HOSTS}\s*\))(?:\s*&&\s*Path(?:Prefix)?\(\s*`[^`]{{0,512}}`\s*\))*$")
_ADDRESS = re.compile(r"^[A-Za-z0-9][A-Za-z0-9.:-]{0,252}$")
ROUTER_KEYS = {"rule", "entrypoints", "tls", "tls.certresolver", "middlewares", "service", "priority"}
SERVICE_KEYS = {"loadbalancer.server.port", "loadbalancer.server.scheme"}
WILDCARD_BINDS = ("", "0.0.0.0", "::")
FILE_HEADER = ("# Generated by Planet Express from the other hosts' traefik labels (docs/designs/multi-host.md, release D).\n"
               "# Edits are overwritten on the next change. To stop it: multi_host.ingress.enabled: false, then restart PE;\n"
               "# PE then removes this file.\n")


def confined(rule: str) -> bool:
    """Whether every request `rule` matches is for a host its Host(..) group names: the rule starts with that group and anything
    after it is joined by && with no top-level ||. An existing router whose rule is not confined is one whose hosts PE cannot
    read (Codex, release D)."""
    rule = rule.strip()
    m = _HOST_GROUP.match(rule)
    if not m:
        return False
    rest = rule[m.end():].strip()
    if not rest:
        return True
    if not rest.startswith("&&"):
        return False
    depth, quoted = 0, False
    for i, ch in enumerate(rest):
        if ch == "`":
            quoted = not quoted
        elif not quoted and ch == "(":
            depth += 1
        elif not quoted and ch == ")":
            depth -= 1
        elif not quoted and depth == 0 and rest.startswith("||", i):
            return False
    return depth == 0 and not quoted


@dataclass(frozen=True)
class TraefikState:
    """What this Traefik already has, from its API, apart from PE's own file."""
    foreign_hosts: frozenset[str]
    blocked: dict                      # entry point -> an existing router on it whose hosts PE cannot read
    names: frozenset[str]              # File-provider router and service names already in use (not PE's)
    entrypoints: frozenset[str]
    middlewares: frozenset[str]
    resolvers: frozenset[str]


@dataclass
class Plan:
    routers: dict = field(default_factory=dict)
    services: dict = field(default_factory=dict)
    routes: list = field(default_factory=list)       # [{host, container, router, service, hosts, url, kept?}]
    skipped: list = field(default_factory=list)      # [{host, container, router, reason}]

    def document(self) -> dict | None:
        if not self.routers:
            return None
        return {"http": {"routers": self.routers, "services": self.services}}


def _get_json(url: str, timeout: float = API_TIMEOUT_S):
    """GET a Traefik API list, every page of it (the API pages at 100 by default: a router on page 2 is still a router, review)."""
    out: list = []
    page = "1"
    for _ in range(MAX_PAGES):
        sep = "&" if "?" in url else "?"
        with urllib.request.urlopen(f"{url}{sep}per_page=100&page={urllib.parse.quote(page)}", timeout=timeout) as resp:  # noqa: S310 -- loopback
            body = json.loads(resp.read(8 * 1024 * 1024))
            nxt = resp.headers.get("X-Next-Page")
        if not isinstance(body, list):
            return body
        out.extend(body)
        # Traefik answers X-Next-Page: 1 on the last page: only a higher page number is a next page (review, release D).
        if not nxt or not nxt.isdigit() or int(nxt) <= int(page):
            return out
        page = nxt
    raise RuntimeError("Traefik's API answered more pages than PE reads")


def read_traefik(api: str, get=_get_json, owned: frozenset[str] = frozenset(), owned_services: frozenset[str] = frozenset()
                 ) -> TraefikState:
    """The current Traefik, from its API. Raises on any failure: no state, no write. `owned`/`owned_services` are the names in
    PE's own file: nothing else is PE's, whatever its name (Codex, release D)."""
    api = api.rstrip("/")
    routers, services = get(api + "/api/http/routers"), get(api + "/api/http/services")
    entrypoints, middlewares = get(api + "/api/entrypoints"), get(api + "/api/http/middlewares")
    foreign, resolvers, names, blocked = set(), set(), set(), {}
    mine = {f"{n}@file" for n in owned}
    for r in routers:
        name = str(r.get("name", ""))
        if name in mine:
            continue
        if name.endswith("@file"):
            names.add(name[:-5])
        rule = str(r.get("rule", ""))
        if confined(rule):
            foreign.update(h.lower() for h in _HOST_RULE.findall(rule))
        else:
            for ep in r.get("entryPoints") or []:
                blocked.setdefault(str(ep), name)
        tls = r.get("tls") if isinstance(r.get("tls"), dict) else {}
        if tls.get("certResolver"):
            resolvers.add(str(tls["certResolver"]))
    for x in services:
        name = str(x.get("name", ""))
        if name.endswith("@file") and name[:-5] not in owned_services:
            names.add(name[:-5])
    return TraefikState(frozenset(foreign), blocked, frozenset(names),
                        frozenset(str(e.get("name")) for e in entrypoints if e.get("name")),
                        frozenset(str(m.get("name")) for m in middlewares if m.get("name")), frozenset(resolvers))


def host_address(alias: str, runner=subprocess.run) -> str | None:
    """The address an SSH alias resolves to (`ssh -G` reads ~/.ssh/config locally; nothing is sent to the host)."""
    try:
        proc = runner(["ssh", "-G", "--", alias], capture_output=True, timeout=5)
    except (OSError, subprocess.TimeoutExpired):
        return None
    for line in (proc.stdout or b"").decode("utf-8", "replace").splitlines():
        key, _, value = line.partition(" ")
        if key == "hostname" and _ADDRESS.match(value.strip()):
            return value.strip()
    return None


def _labelled(container) -> bool:
    labels = container.get("labels") if isinstance(container, dict) and isinstance(container.get("labels"), dict) else {}
    return str(labels.get("traefik.enable", "")).lower() == "true"


def _router_labels(labels: dict) -> tuple[dict[str, dict], dict[str, dict], list[str]]:
    """{router: {key: value}}, {service: {key: value}}, [label keys PE does not forward]."""
    routers: dict[str, dict] = {}
    services: dict[str, dict] = {}
    unsupported = []
    for key, value in labels.items():
        # Only traefik.* is routing: compose's own labels ride along in the collector's record and are not "unforwarded"
        # (live rc14.11: every compose container was listed as having labels PE does not forward).
        if not key.startswith("traefik.") or key == "traefik.enable" or key.startswith("traefik.docker."):
            continue
        m = re.match(r"^traefik\.http\.routers\.([^.]+)\.(.+)$", key)
        if m:
            routers.setdefault(m[1], {})[m[2].lower()] = value
            continue
        m = re.match(r"^traefik\.http\.services\.([^.]+)\.(.+)$", key)
        if m:
            services.setdefault(m[1], {})[m[2].lower()] = value
            continue
        unsupported.append(key)
    return routers, services, unsupported


def plan_routes(hosts: list[dict], traefik: TraefikState, addresses: dict[str, str | None],
                reserved: dict[str, str] | None = None, reserved_names: frozenset[str] = frozenset()) -> Plan:
    """The routes to write, and every labelled router that is not written with why. `hosts` are hosts.json records that are
    reading; `addresses` maps each alias to the address its routes point at; `reserved` maps a host to the route PE is keeping
    for it, and `reserved_names` are the router and service names of kept routes."""
    plan = Plan()
    reserved = reserved or {}
    taken_names = traefik.names | reserved_names
    candidates = []

    def skip(alias, container, router, reason):
        plan.skipped.append({"host": alias, "container": container, "router": router, "reason": reason})

    for rec in hosts:
        alias = rec.get("ssh")
        if not isinstance(alias, str) or not isinstance(rec.get("containers"), list):
            continue
        for c in rec["containers"]:
            if not _labelled(c) or c.get("state") not in (None, "running"):
                continue                           # a container that is not running keeps its route (see RemoteIngress.sync)
            name = c.get("name") if isinstance(c.get("name"), str) else "?"
            routers, services, unsupported = _router_labels(c["labels"])
            if unsupported:
                skip(alias, name, None, "labels PE does not forward: " + ", ".join(sorted(unsupported))[:300])
            if not routers:
                skip(alias, name, None, "no traefik.http.routers labels (PE does not invent a default rule)")
                continue
            address = addresses.get(alias)
            if address is None:
                skip(alias, name, None, f"the address of ssh alias {alias!r} could not be read")
                continue
            for rname, r in sorted(routers.items()):
                reason, built = _build(alias, address, c, rname, r, services, traefik)
                if reason:
                    skip(alias, name, rname, reason)
                else:
                    candidates.append((alias, name, rname, *built))

    count: dict[str, int] = {}
    for cand in candidates:
        for h in cand[3]:
            count[h] = count.get(h, 0) + 1
    for alias, name, rname, hosts_, router, sname, service, url in candidates:
        twice = sorted(h for h in hosts_ if count[h] > 1)
        if twice:
            skip(alias, name, rname, "another remote container claims the same host: " + ", ".join(twice))
            continue
        kept = sorted(h for h in hosts_ if h in reserved)
        if kept:
            skip(alias, name, rname, "served by a route PE is keeping (its host or container is not up): " + ", ".join(kept))
            continue
        rkey = re.sub(r"[^A-Za-z0-9_-]", "-", f"{PREFIX}{alias}--{name}--{rname}")[:150]
        if rkey in plan.routers or rkey in taken_names or sname in taken_names or (
                sname in plan.services and plan.services[sname] != service):
            skip(alias, name, rname, f"its generated name {rkey!r} or {sname!r} is already in use")
            continue
        plan.routers[rkey] = {**router, "service": sname}
        plan.services[sname] = service
        plan.routes.append({"host": alias, "container": name, "router": rkey, "service": sname, "hosts": sorted(hosts_),
                            "url": url, "label": rname})
    return plan


def _build(alias, address, container, rname, r, services, traefik: TraefikState):
    if not _NAME.match(rname) or not _NAME.match(alias):
        return "router or alias name PE does not accept", None
    extra = set(r) - ROUTER_KEYS
    if extra:
        return "router keys PE does not forward: " + ", ".join(sorted(extra)), None
    rule = r.get("rule")
    if not isinstance(rule, str) or not rule or len(rule) > MAX_RULE or any(ord(ch) < 32 for ch in rule):
        return "no usable rule", None
    hosts = {h.lower() for h in _HOST_RULE.findall(rule)}
    if not hosts:
        return "the rule names no Host(...): PE only forwards routes for named hosts", None
    if not _RULE_SHAPE.match(rule.strip()):
        return ("the rule is not Host(...) [|| Host(...)] [&& Path/PathPrefix(...)]: PE forwards only rules that match the hosts "
                "they name"), None
    taken = sorted(hosts & traefik.foreign_hosts)
    if taken:
        return "already served on this host: " + ", ".join(taken), None
    entrypoints = [e.strip() for e in str(r.get("entrypoints", "")).split(",") if e.strip()]
    if not entrypoints:
        return "no entrypoints label", None
    missing = [e for e in entrypoints if e not in traefik.entrypoints]
    if missing:
        return "entry points that do not exist here: " + ", ".join(missing), None
    blocked = [f"{e} ({traefik.blocked[e]})" for e in entrypoints if e in traefik.blocked]
    if blocked:
        return ("an existing route on " + ", ".join(blocked) + " matches hosts PE cannot read, so overlap cannot be ruled out"), None
    middlewares = [m.strip() for m in str(r.get("middlewares", "")).split(",") if m.strip()]
    resolved = []
    for m in middlewares:
        full = m if "@" in m else f"{m}@file"
        if full not in traefik.middlewares:
            return f"middleware {m!r} does not exist here (as {full})", None
        resolved.append(full)
    router: dict = {"rule": rule, "entryPoints": entrypoints}
    if resolved:
        router["middlewares"] = resolved
    tls = str(r.get("tls", "")).lower()
    resolver = r.get("tls.certresolver")
    if tls == "true" or resolver:
        router["tls"] = {}
        if resolver:
            if resolver not in traefik.resolvers:
                return f"certificate resolver {resolver!r} is not in use here", None
            router["tls"] = {"certResolver": resolver}
    if r.get("priority") is not None:
        if not str(r["priority"]).isdigit():
            return "priority is not a number", None
        router["priority"] = int(r["priority"])

    sname_label = r.get("service")
    if sname_label is not None and sname_label not in services:
        return f"service {sname_label!r} is not declared on the container", None
    if sname_label is None and len(services) > 1:
        return "several services and the router names none", None
    svc = services.get(sname_label) if sname_label else (next(iter(services.values())) if services else {})
    bad = set(svc) - SERVICE_KEYS
    if bad:
        return "service keys PE does not forward: " + ", ".join(sorted(bad)), None
    scheme = str(svc.get("loadbalancer.server.scheme", "http")).lower()
    if scheme not in ("http", "https"):
        return f"scheme {scheme!r} is not forwarded", None
    # TCP publications only: an HTTP backend on a UDP port is a route to nothing (Codex, release D).
    ports = [p for p in container.get("ports") or [] if isinstance(p, dict) and isinstance(p.get("host_port"), int)
             and str(p.get("container", "")).endswith("/tcp")]
    want = svc.get("loadbalancer.server.port")
    if want is not None:
        if not str(want).isdigit():
            return "the service port is not a number", None
        ports = [p for p in ports if p.get("container") == f"{int(want)}/tcp"]
        if not ports:
            return f"port {int(want)} is not published on the host: publish it (ports: \"{int(want)}:{int(want)}\")", None
    elif len({p["host_port"] for p in ports}) != 1:
        return ("no service port label and not exactly one published TCP port: set "
                "traefik.http.services.<name>.loadbalancer.server.port"), None
    # Published on every address, or on the very address the route points at (Codex, release D).
    reachable = [p for p in ports if str(p.get("host_ip") or "") in WILDCARD_BINDS or p.get("host_ip") == address]
    if not reachable:
        binds = ", ".join(sorted({str(p.get("host_ip")) for p in ports}))
        return f"the port is published on {binds} only, not on {address}", None
    host = f"[{address}]" if ":" in address else address          # an IPv6 literal goes in brackets (Codex, release D)
    url = f"{scheme}://{host}:{reachable[0]['host_port']}"
    sname = re.sub(r"[^A-Za-z0-9_-]", "-", f"{PREFIX}{alias}--{container.get('name', 'x')}--{reachable[0]['host_port']}")[:150]
    return None, (hosts, router, sname, {"loadBalancer": {"servers": [{"url": url}]}}, url)


def render(document: dict | None) -> str | None:
    if document is None:
        return None
    return FILE_HEADER + yaml.safe_dump(document, sort_keys=True, default_flow_style=False)


def _doc_of(text: str | None) -> dict:
    try:
        doc = yaml.safe_load(text) if text else {}
    except yaml.YAMLError:
        doc = {}
    http = doc.get("http") if isinstance(doc, dict) else None
    http = http if isinstance(http, dict) else {}
    return {"routers": http.get("routers") if isinstance(http.get("routers"), dict) else {},
            "services": http.get("services") if isinstance(http.get("services"), dict) else {}}


def _put(path: Path, text: str | None) -> None:
    if text is None:
        try:
            path.unlink()
        except FileNotFoundError:
            pass
    else:
        write_text_atomic(path, text, 0o644)          # Traefik reads it as its own user


def load_status(path: Path) -> dict:
    try:
        data = json.loads(path.read_text())
    except (OSError, ValueError):
        return {"routes": [], "skipped": []}
    return data if isinstance(data, dict) else {"routes": [], "skipped": []}


class RemoteIngress:
    def __init__(self, cfg, *, lock, notify: Callable[[str], None], state_dir: Path, address=host_address, get=_get_json,
                 clock=time.monotonic, sleep=time.sleep):
        self.cfg, self.lock, self.notify, self.state_dir = cfg, lock, notify, Path(state_dir)
        self.path = Path(cfg.directory) / FILE_NAME
        self._address, self._get, self._clock, self._sleep = address, get, clock, sleep
        self._addresses: dict[str, str | None] = {}
        self._refused: str | None = None           # the sha256 of a file Traefik did not take: not tried again until it changes

    def status_file(self) -> Path:
        return self.state_dir / STATUS_NAME

    def _address_of(self, alias: str) -> str | None:
        if self._addresses.get(alias) is None:
            self._addresses[alias] = self._address(alias)
        return self._addresses[alias]

    def sync(self, data: dict, inventory) -> str:
        """One pass after a collection. Returns what happened, in a word, for the log and the tests."""
        docker_aliases = {e.ssh for e in inventory.hosts if e.ssh and e.docker}
        records = {h.get("ssh"): h for h in data.get("hosts", []) if h.get("ssh") in docker_aliases}
        reading = [h for h in records.values() if h.get("error") is None]
        try:
            current = self.path.read_text()
        except FileNotFoundError:
            current = None
        current_doc = _doc_of(current)
        kept = self._kept(current_doc, load_status(self.status_file()), records)
        reserved = {h: r["router"] for r in kept for h in r.get("hosts", [])}
        try:
            traefik = read_traefik(self.cfg.traefik_api, self._get, owned=frozenset(current_doc["routers"]),
                                   owned_services=frozenset(current_doc["services"]))
        except Exception as exc:  # noqa: BLE001 -- nothing to check a write against: no write
            log.warning("remote routes not synced: Traefik's API could not be read (%s)", type(exc).__name__)
            return "no-traefik"
        addresses = {h["ssh"]: self._address_of(h["ssh"]) for h in reading
                     if any(_labelled(c) for c in h.get("containers") or [])}
        plan = plan_routes(reading, traefik, addresses, reserved,
                           frozenset(r["router"] for r in kept) | frozenset(r["service"] for r in kept))
        for r in kept:
            plan.routers[r["router"]] = current_doc["routers"][r["router"]]
            plan.services[r["service"]] = current_doc["services"][r["service"]]
            plan.routes.append({**r, "kept": True})
        text = render(plan.document())
        if text == current:
            self._refused = None
            write_atomic(self.status_file(), {"at": time.time(), "routes": plan.routes, "skipped": plan.skipped})
            return "unchanged"
        digest = hashlib.sha256((text or "").encode()).hexdigest()
        if digest == self._refused:
            return "refused-before"                 # Traefik did not take exactly this file: wait for something to change
        if not self.lock.try_begin_mutation(OWNER):
            return "busy"
        try:
            _put(self.path, text)
            failed = self._verify(plan.document(), current_doc)
            if failed:
                _put(self.path, current)
                self._refused = digest
                self.notify("⚠️ Routes for other hosts: Traefik did not take " + html.escape(", ".join(sorted(failed))[:500])
                            + ". The previous file is back; nothing changed. PE will not try this again until the labels change.")
                log.error("remote routes rolled back: %s", sorted(failed))
                return "rolled-back"
            self._refused = None
            write_atomic(self.status_file(), {"at": time.time(), "routes": plan.routes, "skipped": plan.skipped})
            self._announce(plan, current_doc)
            return "written"
        finally:
            self.lock.end_mutation(OWNER)

    @staticmethod
    def _kept(current_doc: dict, status: dict, records: dict) -> list[dict]:
        """The routes kept as they are this pass: their host did not answer, or their container is there and not running (Docker
        drops a stopped container's published ports; the route must not flap). Ownership is PE's own record, never a name."""
        out = []
        for r in status.get("routes") or []:
            if not isinstance(r, dict) or r.get("router") not in current_doc["routers"]:
                continue
            if (current_doc["routers"][r["router"]].get("service") != r.get("service")
                    or r.get("service") not in current_doc["services"]):
                continue
            rec = records.get(r.get("host"))
            if rec is None:
                continue                                       # the host left the inventory: its routes go
            if rec.get("error") is not None:
                out.append({k: v for k, v in r.items() if k != "kept"})
                continue
            mine = next((c for c in rec.get("containers") or [] if isinstance(c, dict) and c.get("name") == r.get("container")),
                        None)
            if mine is not None and mine.get("state") not in (None, "running") and _labelled(mine):
                out.append({k: v for k, v in r.items() if k != "kept"})
        return out

    def _announce(self, plan: Plan, previous: dict) -> None:
        new = (plan.document() or {}).get("http", {"routers": {}, "services": {}})
        added = sorted(set(new["routers"]) - set(previous["routers"]))
        removed = sorted(set(previous["routers"]) - set(new["routers"]))
        changed = sorted(n for n in set(new["routers"]) & set(previous["routers"])
                         if new["routers"][n] != previous["routers"][n]
                         or new["services"].get(new["routers"][n].get("service"))
                         != previous["services"].get(previous["routers"][n].get("service")))
        by_name = {r["router"]: r for r in plan.routes}
        lines = [html.escape(f"+ {', '.join(by_name[n]['hosts'])} → {by_name[n]['url']} ({by_name[n]['container']} on "
                             f"{by_name[n]['host']})") for n in added if n in by_name]
        lines += [html.escape(f"~ {', '.join(by_name[n]['hosts'])} → {by_name[n]['url']} (changed)") for n in changed if n in by_name]
        lines += [html.escape(f"− {name}") for name in removed]
        if lines:
            self.notify("🌐 Routes for other hosts changed:\n" + "\n".join(lines[:20]))
        log.info("remote routes written: %d added, %d changed, %d removed", len(added), len(changed), len(removed))

    def _verify(self, document: dict | None, previous: dict) -> set[str]:
        """What Traefik did not take, after waiting for it to load the file: every router PE wrote must be there, enabled, with
        no error and with every field PE wrote; its service must have the URL written; every router PE removed must be gone.
        Contents, not names: right after a change Traefik can still show the OLD router (Codex, release D)."""
        want = (document or {}).get("http", {"routers": {}, "services": {}})
        gone = set(previous["routers"]) - set(want["routers"])
        if not want["routers"] and not gone:
            return set()
        api = self.cfg.traefik_api.rstrip("/")
        deadline = self._clock() + VERIFY_TIMEOUT_S
        bad = set(want["routers"]) | gone
        while self._clock() < deadline:
            self._sleep(1.0)
            try:
                routers = {str(r.get("name")): r for r in self._get(api + "/api/http/routers")}
                services = {str(x.get("name")): x for x in self._get(api + "/api/http/services")}
            except Exception:  # noqa: BLE001 -- keep waiting until the deadline
                continue
            bad = {n for n in gone if f"{n}@file" in routers}
            bad |= {n for n, r in want["routers"].items()
                    if not _applied(routers.get(f"{n}@file"), r, services.get(f"{r['service']}@file"), want["services"][r["service"]])}
            if not bad:
                return set()
        return bad

    def retire_until_done(self, *, retry_s: float = 60, attempts: int = 24 * 60) -> str:
        """retire(), again every `retry_s` while the host is busy (a scan, a change, maintenance): routes must not outlive the
        switch because the host was busy at startup (Codex, release D)."""
        out = "busy"
        for _ in range(attempts):
            out = self.retire()
            if out != "busy":
                return out
            self._sleep(retry_s)
        log.error("could not remove %s: the host stayed busy", self.path)
        return out

    def retire(self) -> str:
        """Ingress turned off: remove PE's file (and its record) under the lock, and say so. Routes do not outlive the switch."""
        if not self.path.exists():
            return "absent"
        if not self.lock.try_begin_mutation(OWNER):
            return "busy"
        try:
            names = sorted(_doc_of(self.path.read_text())["routers"])
            _put(self.path, None)
            try:
                self.status_file().unlink()
            except FileNotFoundError:
                pass
            self.notify("🌐 Routes for other hosts are off (multi_host.ingress.enabled: false): removed "
                        + html.escape(", ".join(names)[:500] or "an empty file") + ".")
            return "removed"
        finally:
            self.lock.end_mutation(OWNER)


def _applied(got: dict | None, want: dict, svc: dict | None, want_svc: dict) -> bool:
    """Whether Traefik shows `want` exactly as written (every field PE writes, and the backend URL)."""
    if got is None or got.get("status") != "enabled" or got.get("error"):
        return False
    if got.get("rule") != want["rule"] or got.get("service") not in (want["service"], f"{want['service']}@file"):
        return False
    if sorted(got.get("entryPoints") or []) != sorted(want["entryPoints"]):
        return False
    if sorted(got.get("middlewares") or []) != sorted(want.get("middlewares") or []):
        return False
    if "tls" in want:
        tls = got.get("tls") if isinstance(got.get("tls"), dict) else None
        if tls is None or (tls.get("certResolver") or None) != (want["tls"].get("certResolver") or None):
            return False
    elif got.get("tls"):
        return False
    if "priority" in want and got.get("priority") != want["priority"]:
        return False
    urls = [x.get("url") for x in ((svc or {}).get("loadBalancer") or {}).get("servers") or []]
    return urls == [x["url"] for x in want_svc["loadBalancer"]["servers"]]
