"""Routes for the other hosts' containers on this host's Traefik (docs/designs/multi-host.md, release D).

Traefik's Docker provider watches one daemon, this host's. A container on another host with `traefik.*` labels is invisible to it.
PE already reads every host's labels (release A), so PE forwards them: each remote router becomes an entry in ONE generated file in
Traefik's File-provider directory (`pe-remote.yml`), pointing at the host's address and the port the container publishes there. The
operator's own files in that directory are never written.

This changes the ingress, so it is built to fail safe (second review, like the AdGuard network-guard exception):

  * Off unless `multi_host.ingress.enabled`; turned off, PE removes its file at the next start (routes do not outlive the switch).
  * A route is written only if it cannot take traffic from anything that already works:
      - its rule is confined to the hosts it names: Host(..) [|| Host(..)], optionally narrowed by && Path/PathPrefix(..);
      - no host it names is served by a router PE did not write, by a route PE is keeping, or by two remote containers;
      - no existing router on its entry points has a rule whose hosts PE cannot read (HostRegexp, multi-argument Host, no Host):
        overlap with such a rule cannot be ruled out, so that entry point takes no remote route;
      - its generated router and service names are not names already used in the File provider;
      - every entry point, middleware and certificate resolver it names already exists in this Traefik;
      - its port is published over TCP on an address reachable at the host's SSH address.
    Anything PE does not translate is not written, and every refusal is kept with its reason and shown on the Hosts tab.
  * The file is built as data and dumped by the YAML library: no label value becomes YAML syntax.
  * A write takes the host-mutation lock, is atomic, and is then checked against Traefik's own API, field by field (rule, service,
    entry points, middlewares, TLS, priority, backend URL; removed routers gone): anything Traefik did not take puts the previous
    file back, is announced, and the same file is not tried again until something changes.
  * A host that does not answer, or a container that is not running (Docker drops its published ports), keeps its routes.
  * Which host and container a route belongs to is PE's own record (state/remote_routes.json), never inferred from a name.
"""

